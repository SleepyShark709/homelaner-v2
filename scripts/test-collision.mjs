import assert from 'node:assert/strict';
import { moveAndSlide, firstHit } from '../src/game/collision.ts';
const floor = { id: 'floor', min: [-100, -1, -100], max: [100, 0, 100] };
const wall = { id: 'wall', min: [5, 0, -10], max: [6, 30, 10] };
const close = (actual, expected, tolerance = .005) => assert.ok(Math.abs(actual - expected) < tolerance, `${actual} != ${expected}`);
const fast = moveAndSlide([0, 2, 0], [70, 0, 0], [floor, wall]);
close(fast.position[0], 4.64);
assert.equal(fast.normals[0][0], -1);
const slide = moveAndSlide([0, 2, 0], [10, 0, 4], [floor, wall]);
close(slide.position[0], 4.64); close(slide.position[2], 4);
const landing = moveAndSlide([0, 40, 0], [0, -80, 0], [floor]);
close(landing.position[1], 0);
assert.equal(landing.normals[0][1], 1);
const resting = moveAndSlide([0, .001, 0], [2, -.01, 0], [floor]);
close(resting.position[0], 2); close(resting.position[1], 0);
const roof = { id: 'ceiling', min: [-10, 5, -10], max: [10, 6, 10] };
close(moveAndSlide([0, 0, 0], [0, 20, 0], [roof]).position[1], 3.08);
const corner = { id: 'corner', min: [-10, 0, 5], max: [10, 30, 6] };
const cornerMove = moveAndSlide([0, 2, 0], [20, 0, 20], [wall, corner]);
close(cornerMove.position[0], 4.64); close(cornerMove.position[2], 4.64);
assert.equal(firstHit([0, 2, 0], [0, 0, 2], [wall]), null);
assert.equal(firstHit([0, 2, 0], [10, 0, 0], [wall]).id, 'wall');
console.log('8 collision scenarios passed: high-speed wall, sliding, landing, ground motion, ceiling, corner, parallel ray, camera ray.');
